class WorldBakes:
    """The landscape bake records (assets/build/world/<Set>.json), read once per set on demand:
    a paste with no world lines never touches the gitignored build tree."""

    def __init__(self, root: str):
        self.root = root
        self.cache: dict[str, dict | None] = {}

    def path(self, set_name: str) -> str:
        return os.path.join(self.root, f"{set_name}.json")

    def shown(self, set_name: str) -> str:
        try:
            return os.path.relpath(self.path(set_name), cfg.REPO_ROOT)
        except ValueError:  # a --bake-root on another drive has no relative form
            return self.path(set_name)

    def get(self, set_name: str) -> dict | None:
        if set_name not in self.cache:
            record = None
            if os.path.isfile(self.path(set_name)):
                with open(self.path(set_name), "r", encoding="utf-8") as fh:
                    record = json.load(fh)
            self.cache[set_name] = record if isinstance(record, dict) else None
        return self.cache[set_name]


def world_axis_ok(harvested: float, baked: float) -> bool:
    return abs(harvested - baked) <= max(WORLD_SIZE_TOLERANCE_STUDS, WORLD_SIZE_TOLERANCE_SHARE * abs(baked))


def world_size_problem(set_name: str, mesh_name: str, mesh: dict, size: list[float], bakes: WorldBakes) -> str | None:
    """Why this mesh must not be merged, or None. The generator's coordinates are world studs, so
    the template only puts the landscape where it was designed if the importer kept the mesh at
    1 glTF unit = 1 stud; Studio's Size against the baked bounding box is the proof of that. A size
    that cannot be checked is treated like a wrong one: an unchecked mesh never reaches a template."""
    bake = bakes.get(set_name)
    if bake is None:
        return f"no bake record at {bakes.shown(set_name)} to check the size against; run {WORLD_BUILD_CMD} or pass --bake-root"
    baked = (bake.get("meshes") or {}).get(mesh_name)
    if not isinstance(baked, dict) or not isinstance(baked.get("size"), list) or len(baked["size"]) != 3:
        return "not in the bake record (or it has no size there), so its size cannot be checked"
    if baked.get("sha256") != mesh.get("sha256"):
        return "the bake record was rebuilt since this mesh was uploaded (sha256 differs); run upload_world.py again"
    baked_size = [float(v) for v in baked["size"]]
    if all(world_axis_ok(size[i], baked_size[i]) for i in range(3)):
        return None
    ratios = ", ".join(f"{size[i] / baked_size[i]:.4g}" if baked_size[i] else "-" for i in range(3))
    return f"harvested size {size} is not the baked size {baked_size} (x {ratios}); the importer rescaled it"


def merge_world_mesh(assets: dict, rec: dict, force: bool, bakes: WorldBakes, size_problems: list[str]) -> bool:
    """One landscape mesh, exactly like a path piece (one MeshPart; MeshId, Size, offset recorded as
    Studio reported them, gen_templates.py applies the importer's turn), plus the size check."""
    set_name, mesh_name = rec.get("set"), rec.get("mesh")
    mesh = ((assets.get(cfg.WORLD_KEY, {}).get(set_name) or {}).get("meshes") or {}).get(mesh_name)
    if mesh is None:
        warn(f"no world entry for {set_name}/{mesh_name}; line skipped")
        return False
    label = f"world {set_name} {mesh_name}"
    expected = int(mesh.get("assetId", 0))
    got = int(str(rec.get("assetId", "0")) or 0)
    if expected != got and not force:
        warn(f"{label}: printed asset {got} but Assets.json has {expected} (stale paste? use --force); skipped")
        return False
    parts = rec.get("parts") or []
    if len(parts) != 1:
        warn(f"{label}: expected exactly one MeshPart, got {len(parts)}; skipped")
        return False
    part = parts[0]
    mesh_id = int(str(part.get("meshId", "0")) or 0)
    if mesh_id == 0:
        warn(f"{label}: MeshPart has no MeshId; skipped")
        return False
    size = [float(v) for v in part.get("size", [0, 0, 0])]
    offset = [float(v) for v in part.get("offset", [0, 0, 0])]
    problem = world_size_problem(set_name, mesh_name, mesh, size, bakes)
    if problem:
        size_problems.append(f"{label}: {problem}")
        warn(f"{label}: {problem}; NOT merged")
        return False
    if part.get("rotated"):
        warn(f"{label}: MeshPart is rotated relative to the model beyond the importer's 180 deg turn")
    # Not part of the contract's gate, so only a warning: the template trusts this offset, and it
    # should be the baked centre seen through the importer's turn (x and z negated).
    baked = bakes.get(set_name)["meshes"][mesh_name]
    centre = baked.get("centre")
    if isinstance(centre, list) and len(centre) == 3:
        wanted = [-float(centre[0]), float(centre[1]), -float(centre[2])]
        slack = [max(WORLD_SIZE_TOLERANCE_STUDS, WORLD_SIZE_TOLERANCE_SHARE * size[i]) for i in range(3)]
        if not all(abs(offset[i] - wanted[i]) <= slack[i] for i in range(3)):
            warn(
                f"{label}: harvested offset {offset} is not the baked centre through the importer's turn {wanted};"
                " merged as Studio reported it, check where it lands"
            )
    mesh.update({"meshId": mesh_id, "size": size, "offset": offset})
    log(f"{label}: mesh {mesh_id}, size {size} matches the bake")
    return True


def list_missing(assets: dict, props: bool) -> list[str]:
    missing = []
    group, prefix = ("props", "props/") if props else ("eras", "")
    for era, model, index, stage in cfg.iter_stages(assets, group):
        if int(stage.get("modelAssetId", 0)) != 0 and not cfg.stage_harvested(stage):
            missing.append(f"{prefix}{era}/{model} S{index}")
    for kit in [] if props else sorted(assets.get("textures", {})):
        tex = assets["textures"][kit]
        if int(tex.get("vipSwatchAssetId", 0)) != 0 and int(tex.get("vipImageId", 0)) == 0:
            missing.append(f"VIP swatch {kit}")
    missing += [
        f"path texture {era} {variant + ' ' if variant else ''}{layer}"
        for era, variant, layer, _ in pending_path_textures(assets)
    ]
    pieces = pending_path_pieces(assets)
    if pieces:
        missing.append(f"{len(pieces)} path piece mesh(es)")
    missing += [f"world palette {set_name}" for set_name, _ in pending_world_textures(assets)]
    missing += [f"world {set_name} {mesh_name}" for set_name, mesh_name, _ in pending_world_meshes(assets)]
    return missing


def merge(assets: dict, text: str, force: bool, props: bool, world_bake_root: str = WORLD_BAKE_DIR) -> int:
    records = parse_records(text)
    if not records:
        warn("no [HARVEST] lines found (copy the whole Output window after running harvest.luau)")
        return 1
    models = swatches = path_textures = path_pieces = world_textures = world_meshes = 0
    world_bakes = WorldBakes(world_bake_root)
    world_size_problems: list[str] = []
    for rec in records:
        kind = rec.get("kind")
        if kind == "pathTexture":
            path_textures += merge_path_texture(assets, rec, force)
        elif kind == "pathPiece":
            path_pieces += merge_path_piece(assets, rec, force)
        elif kind == "worldTexture":
            world_textures += merge_world_texture(assets, rec, force)
        elif kind == "worldMesh":
            world_meshes += merge_world_mesh(assets, rec, force, world_bakes, world_size_problems)
        elif props:
            if kind == "prop":
                models += merge_model(assets, rec, force, "props")
            else:
                warn(f"{kind!r} line skipped (--props merges only prop lines; rerun without --props for it)")
        elif kind == "model":
            models += merge_model(assets, rec, force)
        elif kind == "swatch":
            swatches += merge_swatch(assets, rec, force)
        elif kind == "prop":
            warn("prop line skipped (rerun with --props to merge it)")
        else:
            warn(f"unknown record kind {kind!r}; skipped")
    cfg.save_assets(assets)
    if props:
        log(f"merged {models} prop stage(s) into {os.path.relpath(cfg.ASSETS_PATH, cfg.REPO_ROOT)}")
    else:
        log(f"merged {models} model stage(s) and {swatches} swatch(es) into {os.path.relpath(cfg.ASSETS_PATH, cfg.REPO_ROOT)}")
    if path_textures or path_pieces:
        log(f"merged {path_textures} path texture(s) and {path_pieces} path piece mesh(es)")
    if world_textures or world_meshes or world_size_problems:
        log(f"merged {world_textures} world palette(s) and {world_meshes} world mesh(es)")
    missing = list_missing(assets, props)
    if missing:
        log("still missing harvest data: " + ", ".join(missing))
    else:
        commands = ["py tools/assets/gen_templates.py" + (" --props" if props else "")]
        if path_textures or path_pieces:
            commands.append("py tools/assets/gen_templates.py --paths")
        if world_textures or world_meshes:
            commands.append("py tools/assets/gen_templates.py --world")
        log("every uploaded asset is harvested; next: " + ", then ".join(commands))
    if world_size_problems:
        # Last, and with a failing exit code: everything else is merged and saved above, but a
        # landscape mesh whose size is not the baked one must stop the pipeline run that follows.
        for line in world_size_problems:
            warn(f"SIZE CHECK: {line}")
        warn(f"{len(world_size_problems)} world mesh(es) failed the size check and were not merged")
        return 1
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emit", action="store_true", help="write harvest.luau instead of merging")
    parser.add_argument("--all", action="store_true", help="with --emit: include already-harvested assets")
    parser.add_argument("--file", help="read Output text from this file instead of the clipboard")
    parser.add_argument("--force", action="store_true", help="merge lines whose asset id differs from Assets.json")
    parser.add_argument("--props", action="store_true", help="emit / merge city-dressing props instead of buildings")
    parser.add_argument("--assets-json", help="read and write this Assets.json instead of src/shared/Config/Assets.json")
    parser.add_argument("--luau", help="with --emit: write the snippet here instead of tools/assets/harvest.luau")
    parser.add_argument("--bake-root", help="landscape bake records to check world mesh sizes against, instead of assets/build/world")
    args = parser.parse_args(argv)
    cfg.use_assets_path(args.assets_json)

    if not os.path.isfile(cfg.ASSETS_PATH):
        warn(f"{os.path.relpath(cfg.ASSETS_PATH, cfg.REPO_ROOT)} does not exist yet; run upload_models.py first")
        return 1
    assets = cfg.load_assets()
    if args.emit:
        return emit(assets, args.all, args.props, os.path.abspath(args.luau) if args.luau else LUAU_PATH)
    if args.file:
        with open(args.file, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    else:
        text = read_clipboard()
    bake_root = os.path.abspath(args.bake_root) if args.bake_root else WORLD_BAKE_DIR
    return merge(assets, text, args.force, args.props, bake_root)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
